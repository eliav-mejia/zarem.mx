#!/usr/bin/env python3
"""Create / update colegio_la_florida/tienda/<slug>/index.html for every active product in colegio_la_florida/db/productos.json,
and rewrite sitemap.xml.

    python tools/generar-paginas-producto.py

The page is rendered by renderProduct() in js/tienda.jsx, which reads the JSON at load time, so price, colour or
description changes need no regeneration for visitors. Re-run after adding a product or changing slug, name, short,
description, price_mxn or variants (copied into <head> and schema.org for search engines).
Product folders whose slug is no longer in the database are listed, not deleted.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = 'https://zarem.mx'
OUT = ROOT / 'colegio_la_florida' / 'tienda'

# Static pages for sitemap.xml (bolsa is excluded: no value for search engines).
STATIC_PAGES = ['/', '/cum/', '/colegio_la_florida/', '/colegio_la_florida/tienda/', '/colegio_la_florida/como-comprar/', '/colegio_la_florida/contacto/', '/colegio_la_florida/terminos/', '/colegio_la_florida/privacidad/']

TEMPLATE = """<!DOCTYPE html>
<html lang="es-MX">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{title}</title>
    <meta name="description" content="{description}">
    <link rel="canonical" href="{url}">
    <meta property="og:title" content="{title}">
    <meta property="og:description" content="{description}">
    <meta property="og:url" content="{url}">
    <meta property="og:type" content="product">
    <meta property="og:site_name" content="Zarem">
    <meta property="og:locale" content="es_MX">
    <meta property="og:image" content="{image}">
    <meta name="twitter:card" content="summary_large_image">
    <link rel="icon" href="/img/favicon.svg" type="image/svg+xml">
    <meta name="theme-color" content="#ffffff">
    <script type="application/ld+json">{jsonld}</script>
    <script type="application/ld+json">{breadcrumb}</script>

    <script src="https://cdn.tailwindcss.com"></script>
    <script src="/js/tailwind.config.js"></script>
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=Bodoni+Moda:opsz,wght@6..96,400&family=Inter:wght@300;400;500&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="/css/site.css">

    <script crossorigin src="https://cdnjs.cloudflare.com/ajax/libs/react/18.2.0/umd/react.production.min.js"></script>
    <script crossorigin src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.2.0/umd/react-dom.production.min.js"></script>
    <script src="https://cdnjs.cloudflare.com/ajax/libs/babel-standalone/7.23.5/babel.min.js"></script>
</head>
<body>

    <div id="root">
        <noscript>
            <h1>{h1}</h1>
            <p>{description}</p>
            <nav aria-label="Colegio La Florida">
                <ul>
                    <li><a href="/colegio_la_florida/tienda/">Tienda de uniformes del Colegio La Florida</a></li>
                    <li><a href="/colegio_la_florida/como-comprar/">Cómo comprar</a></li>
                    <li><a href="/colegio_la_florida/contacto/">Tienda y contacto</a></li>
                </ul>
            </nav>
        </noscript>
    </div>

    <script type="text/babel" src="/js/layout.jsx"></script>
    <script type="text/babel" src="/js/tienda.jsx"></script>
    <script type="text/babel">
        // Generated by tools/generar-paginas-producto.py. The product is found from this page's URL.
        renderProduct();
    </script>
</body>
</html>
"""

FIT = {'nina': 'niña', 'nino': 'niño', 'unisex': 'niña y niño'}
DESCRIPTION_MAX = 160  # what Google shows of the meta description
DESCRIPTION_TAIL = 'Uniforme oficial del Colegio La Florida en Zarem.'


def page_description(p):
    # short + description, whole sentences only, up to 160 characters; short ones get the school and brand.
    text = ''
    for sentence in re.split(r'(?<=\.) ', f"{p['short'].rstrip('.')}. {p['description']}"):
        if len(text) + len(sentence) + 1 > DESCRIPTION_MAX:
            break
        text = f'{text} {sentence}'.strip()
    if len(text) + len(DESCRIPTION_TAIL) + 1 <= DESCRIPTION_MAX:
        text = f'{text} {DESCRIPTION_TAIL}'
    return text


def main():
    products = json.loads((ROOT / 'colegio_la_florida' / 'db' / 'productos.json').read_text(encoding='utf-8'))['products']
    active = [p for p in products if p.get('active', True)]

    for p in active:
        url = f"{SITE}/colegio_la_florida/tienda/{p['slug']}/"
        title = f"{p['name']} · Uniforme Colegio La Florida · Zarem"
        jsonld = {
            '@context': 'https://schema.org', '@type': 'Product',
            'name': p['name'], 'sku': p['sku'], 'description': p['description'],
            'brand': {'@type': 'Brand', 'name': 'Zarem'}, 'image': SITE + p['image'],
            'audience': {'@type': 'PeopleAudience', 'suggestedGender': {'nina': 'female', 'nino': 'male'}.get(p['fit'], 'unisex')},
            'offers': {
                '@type': 'Offer', 'url': url, 'priceCurrency': 'MXN', 'price': p['price_mxn'],
                'availability': 'https://schema.org/InStock' if p['availability'] == 'existencia' else 'https://schema.org/PreOrder',
                'itemCondition': 'https://schema.org/NewCondition',
            },
        }
        # Price by size (variants): publish the range.
        prices = [v['price_mxn'] for v in p.get('variants', [])]
        if prices and max(prices) != min(prices):
            offer = jsonld['offers']
            del offer['price']
            offer.update({'@type': 'AggregateOffer', 'lowPrice': min(prices), 'highPrice': max(prices), 'offerCount': len(prices)})
        out = OUT / p['slug'] / 'index.html'
        out.parent.mkdir(parents=True, exist_ok=True)
        breadcrumb = {
            '@context': 'https://schema.org', '@type': 'BreadcrumbList',
            'itemListElement': [
                {'@type': 'ListItem', 'position': 1, 'name': 'Zarem', 'item': f'{SITE}/'},
                {'@type': 'ListItem', 'position': 2, 'name': 'Colegio La Florida', 'item': f'{SITE}/colegio_la_florida/'},
                {'@type': 'ListItem', 'position': 3, 'name': 'Tienda', 'item': f'{SITE}/colegio_la_florida/tienda/'},
                {'@type': 'ListItem', 'position': 4, 'name': p['name'], 'item': url},
            ],
        }
        out.write_text(TEMPLATE.format(
            title=html.escape(title), description=html.escape(page_description(p)), url=url, image=SITE + p['image'],
            h1=html.escape(f"{p['name']} · Uniforme del Colegio La Florida"),
            jsonld=json.dumps(jsonld, ensure_ascii=False).replace('</', '<\\/'),
            breadcrumb=json.dumps(breadcrumb, ensure_ascii=False).replace('</', '<\\/'),
        ), encoding='utf-8', newline='\n')
        print(f"ok   colegio_la_florida/tienda/{p['slug']}/")

    slugs = {p['slug'] for p in active}
    for d in OUT.iterdir():
        if d.is_dir() and d.name not in slugs:
            print(f"OJO  colegio_la_florida/tienda/{d.name}/ ya no está en la base de datos: bórrala y añade la ruta a MOVED en 404.html")

    urls = STATIC_PAGES + [f"/colegio_la_florida/tienda/{p['slug']}/" for p in active]
    (ROOT / 'sitemap.xml').write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + ''.join(f'  <url><loc>{SITE}{u}</loc></url>\n' for u in urls) + '</urlset>\n', encoding='utf-8', newline='\n')
    print(f"ok   sitemap.xml ({len(urls)} URLs)")


if __name__ == '__main__':
    main()
